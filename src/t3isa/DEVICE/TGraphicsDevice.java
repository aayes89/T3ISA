    private static void putGlyph(byte[] font, int character, int... rows) {
        int offset = character * 16;

        for (int i = 0; i < 16; i++) {
            font[offset + i] = (byte) rows[i];
        }
    }

    /*
     * Operación gráfica general.
     *
     * command:
     *
     * 1  = pixel
     * 2  = clear
     * 3  = line
     * 4  = rect
     * 5  = fill rect
     * 6  = circle
     * 7  = fill circle
     * 8  = drawChar
     */
    public void graphics(int command, int a, int b, int c, int d, int e, int f) {

        switch (command) {
            case 1:
                setPixel(a, b, c);
                break;

            case 2:
                clear(a);
                break;

            case 3:
                drawLine(a, b, c, d, e);
                break;

            case 4:
                drawRect(a, b, c, d, e);
                break;

            case 5:
                fillRect(a, b, c, d, e);
                break;

            case 6:
                drawCircle(a, b, c, d);
                break;

            case 7:
                fillCircle(a, b, c, d);
                break;

            case 8:
                drawChar(a, // character
                        b, // x
                        c, // y
                        d, // scale
                        e, // foreground
                        f // background
                );
                break;
        }
    }

